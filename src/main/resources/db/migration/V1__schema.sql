
-- =========================================
-- SCHEMA DO REINO
-- =========================================

CREATE SCHEMA IF NOT EXISTS reino;

CREATE TABLE IF NOT EXISTS reino.vilas (
                                           id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           nome VARCHAR(100) NOT NULL,
    regiao VARCHAR(50) NOT NULL,
    populacao INT,
    status VARCHAR(20)
    );

CREATE TABLE IF NOT EXISTS reino.habitantes (
                                                id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                nome VARCHAR(100) NOT NULL,
    idade INT,
    profissao VARCHAR(80),
    vila_id INT,
    status VARCHAR(20),
    CONSTRAINT fk_habitante_vila
    FOREIGN KEY (vila_id) REFERENCES reino.vilas(id)
    );

CREATE TABLE IF NOT EXISTS reino.soldados (
                                              id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                              nome VARCHAR(100) NOT NULL,
    nivel INT,
    classe VARCHAR(50),
    vila_id INT,
    status VARCHAR(20),
    CONSTRAINT fk_soldado_vila
    FOREIGN KEY (vila_id) REFERENCES reino.vilas(id)
    );

CREATE TABLE IF NOT EXISTS reino.armas (
                                           id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           nome VARCHAR(100) NOT NULL,
    tipo VARCHAR(50),
    poder INT,
    raridade VARCHAR(30),
    soldado_id INT,
    CONSTRAINT fk_arma_soldado
    FOREIGN KEY (soldado_id) REFERENCES reino.soldados(id)
    );

CREATE TABLE IF NOT EXISTS reino.recursos (
                                              id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                              nome VARCHAR(100),
    tipo VARCHAR(50),
    quantidade INT,
    vila_id INT,
    CONSTRAINT fk_recurso_vila
    FOREIGN KEY (vila_id) REFERENCES reino.vilas(id)
    );

CREATE TABLE IF NOT EXISTS reino.entregas (
                                              id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                              recurso_id INT,
                                              origem_vila_id INT,
                                              destino_vila_id INT,
                                              quantidade INT,
                                              data_entrega DATE,
                                              status VARCHAR(20),
    CONSTRAINT fk_entrega_recurso
    FOREIGN KEY (recurso_id) REFERENCES reino.recursos(id),
    CONSTRAINT fk_entrega_origem
    FOREIGN KEY (origem_vila_id) REFERENCES reino.vilas(id),
    CONSTRAINT fk_entrega_destino
    FOREIGN KEY (destino_vila_id) REFERENCES reino.vilas(id)
    );

CREATE TABLE IF NOT EXISTS reino.criaturas (
                                               id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                               nome VARCHAR(100) NOT NULL,
    tipo VARCHAR(50),
    nivel INT,
    regiao VARCHAR(50),
    status VARCHAR(20)
    );

CREATE TABLE IF NOT EXISTS reino.mensagens (
                                               id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                               remetente VARCHAR(100),
    destinatario VARCHAR(100),
    assunto VARCHAR(150),
    conteudo VARCHAR(2000),
    data_envio TIMESTAMP,
    prioridade VARCHAR(20)
    );

CREATE TABLE IF NOT EXISTS reino.registros_corrompidos (
                                                           id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                           tipo_registro VARCHAR(50),
    registro_id INT,
    regiao VARCHAR(50),
    nivel_corrupcao INT,
    data_corrupcao DATE,
    status VARCHAR(20)
    );


-- =========================================
-- SCHEMA DO JOGO
-- =========================================

CREATE SCHEMA IF NOT EXISTS jogo;

CREATE TABLE IF NOT EXISTS jogo.capitulos (
                                              id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                              numero INT NOT NULL UNIQUE,
                                              nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(2000),
    conceito_principal VARCHAR(100),
    recompensa VARCHAR(100)
    );

CREATE TABLE IF NOT EXISTS jogo.desafios (
                                             id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                             capitulo_id INT NOT NULL,
                                             ordem INT NOT NULL,
                                             titulo VARCHAR(150) NOT NULL,
    descricao VARCHAR(2000),
    objetivo VARCHAR(1000),
    dificuldade INT,
    conceito_sql VARCHAR(100),
    xp INT NOT NULL,
    ouro INT NOT NULL,
    consulta_gabarito VARCHAR(5000) NOT NULL,
    ordem_importa BOOLEAN DEFAULT FALSE,

    CONSTRAINT fk_desafio_capitulo
    FOREIGN KEY (capitulo_id) REFERENCES jogo.capitulos(id),

    CONSTRAINT uk_desafio_ordem
    UNIQUE (capitulo_id, ordem),

    CONSTRAINT ck_desafio_dificuldade
    CHECK (dificuldade BETWEEN 1 AND 5)
    );

CREATE TABLE IF NOT EXISTS jogo.dicas (
                                          id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          desafio_id INT NOT NULL,
                                          nivel INT NOT NULL,
                                          texto VARCHAR(1000) NOT NULL,
    custo_ouro INT NOT NULL,

    CONSTRAINT fk_dica_desafio
    FOREIGN KEY (desafio_id)
    REFERENCES jogo.desafios(id)
    ON DELETE CASCADE,

    CONSTRAINT uk_dica_nivel
    UNIQUE (desafio_id, nivel),

    CONSTRAINT ck_dica_nivel
    CHECK (nivel BETWEEN 1 AND 3)
    );

CREATE TABLE IF NOT EXISTS jogo.itens (
                                          id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          nome VARCHAR(100) NOT NULL UNIQUE,
    descricao VARCHAR(1000),
    tipo VARCHAR(50),
    capitulo_desbloqueio INT,
    image_url VARCHAR(255),

    CONSTRAINT fk_item_capitulo
    FOREIGN KEY (capitulo_desbloqueio)
    REFERENCES jogo.capitulos(id)
    );

CREATE TABLE IF NOT EXISTS jogo.conquistas (
                                               id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                               nome VARCHAR(100) NOT NULL UNIQUE,
    descricao VARCHAR(500),
    image_url VARCHAR(255)
    );

CREATE TABLE IF NOT EXISTS jogo.jogadores (
                                              id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                              nome VARCHAR(100) NOT NULL,
    xp INT NOT NULL DEFAULT 0,
    ouro INT NOT NULL DEFAULT 0,
    nivel INT NOT NULL DEFAULT 1,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

CREATE TABLE IF NOT EXISTS jogo.conquistas_jogador (
                                                       jogador_id BIGINT NOT NULL,
                                                       conquista_id INT NOT NULL,
                                                       desbloqueada_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                                       CONSTRAINT pk_conquistas_jogador
                                                       PRIMARY KEY (jogador_id, conquista_id),

    CONSTRAINT fk_conquistas_jogador_jogador
    FOREIGN KEY (jogador_id) REFERENCES jogo.jogadores(id),

    CONSTRAINT fk_conquistas_jogador_conquista
    FOREIGN KEY (conquista_id) REFERENCES jogo.conquistas(id)
    );

CREATE TABLE IF NOT EXISTS jogo.recompensas_desafio (
                                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                        desafio_id BIGINT NOT NULL,
                                                        item_id BIGINT,
                                                        quantidade INT NOT NULL,
                                                        conquista_id INT,

                                                        CONSTRAINT fk_recompensa_desafio
                                                        FOREIGN KEY (desafio_id)
    REFERENCES jogo.desafios(id)
    ON DELETE CASCADE,

    CONSTRAINT fk_recompensa_item
    FOREIGN KEY (item_id) REFERENCES jogo.itens(id),

    CONSTRAINT fk_recompensa_conquista
    FOREIGN KEY (conquista_id) REFERENCES jogo.conquistas(id),

    CONSTRAINT ck_recompensa_quantidade
    CHECK (
(item_id IS NOT NULL AND quantidade > 0)
    OR
(item_id IS NULL AND quantidade = 0)
    ),

    CONSTRAINT ck_recompensa_conteudo
    CHECK (item_id IS NOT NULL OR conquista_id IS NOT NULL)
    );

CREATE TABLE IF NOT EXISTS jogo.blocos_desafio (
                                                   id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                   desafio_id INT NOT NULL,
                                                   ordem INT NOT NULL,
                                                   texto VARCHAR(500) NOT NULL,

    CONSTRAINT fk_blocos_desafio
    FOREIGN KEY (desafio_id)
    REFERENCES jogo.desafios(id)
    ON DELETE CASCADE,

    CONSTRAINT uk_blocos_desafio_ordem
    UNIQUE (desafio_id, ordem)
    );

CREATE TABLE IF NOT EXISTS jogo.carteira_jogador (
                                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                     jogador_id BIGINT NOT NULL UNIQUE,
                                                     ouro INT NOT NULL DEFAULT 0,

                                                     CONSTRAINT ck_carteira_ouro
                                                     CHECK (ouro >= 0)
    );

CREATE TABLE IF NOT EXISTS jogo.dicas_compradas (
                                                    jogador_id INT NOT NULL,
                                                    dica_id INT NOT NULL,
                                                    desafio_id INT NOT NULL,
                                                    comprado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                                                    CONSTRAINT pk_dicas_compradas
                                                    PRIMARY KEY (jogador_id, dica_id),

    CONSTRAINT fk_dicas_compradas_jogador
    FOREIGN KEY (jogador_id) REFERENCES jogo.jogadores(id),

    CONSTRAINT fk_dicas_compradas_dica
    FOREIGN KEY (dica_id) REFERENCES jogo.dicas(id)
    );

CREATE TABLE IF NOT EXISTS jogo.inventario_jogador (
                                                       jogador_id BIGINT NOT NULL,
                                                       item_id BIGINT NOT NULL,
                                                       quantidade INT NOT NULL DEFAULT 0,

                                                       CONSTRAINT pk_inventario_jogador
                                                       PRIMARY KEY (jogador_id, item_id),

    CONSTRAINT fk_inventario_jogador_jogador
    FOREIGN KEY (jogador_id) REFERENCES jogo.jogadores(id),

    CONSTRAINT fk_inventario_jogador_item
    FOREIGN KEY (item_id) REFERENCES jogo.itens(id),

    CONSTRAINT chk_inventario_quantidade
    CHECK (quantidade >= 0)
    );

CREATE TABLE IF NOT EXISTS jogo.progresso_desafios (
                                                       id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                       jogador_id INT NOT NULL,
                                                       desafio_id INT NOT NULL,
                                                       concluido BOOLEAN NOT NULL DEFAULT FALSE,
                                                       concluido_em TIMESTAMP,

                                                       CONSTRAINT fk_progresso_jogador
                                                       FOREIGN KEY (jogador_id) REFERENCES jogo.jogadores(id),

    CONSTRAINT fk_progresso_desafio
    FOREIGN KEY (desafio_id) REFERENCES jogo.desafios(id),

    CONSTRAINT uk_progresso_jogador_desafio
    UNIQUE (jogador_id, desafio_id)
    );
