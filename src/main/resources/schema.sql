-- SCHEMA DO JOGO
-- ___________________

CREATE SCHEMA IF NOT EXISTS jogo;

CREATE TABLE IF NOT EXISTS jogo.capitulos (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero INT NOT NULL UNIQUE,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(2000),
    conceito_principal VARCHAR(100),
    recompensa VARCHAR(100)
    );

CREATE TABLE IF NOT EXISTS jogo.desafios (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capitulo_id INT NOT NULL,
    ordem INT NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    descricao VARCHAR(2000),
    objetivo VARCHAR(1000),
    dificuldade INT,
    conceito_sql VARCHAR(100),
    xp INT NOT NULL,
    ouro INT NOT NULL,
    consulta_gabarito VARCHAR(5000) NOT NULL,
    ordem_importa BOOLEAN DEFAULT FALSE,

    CONSTRAINT fk_desafio_capitulo
    FOREIGN KEY (capitulo_id)
    REFERENCES jogo.capitulos(id),

    CONSTRAINT uk_desafio_ordem
    UNIQUE (capitulo_id, ordem),

    CONSTRAINT ck_desafio_dificuldade
    CHECK (dificuldade BETWEEN 1 AND 5)
    );


CREATE TABLE IF NOT EXISTS jogo.dicas (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    desafio_id INT NOT NULL,
    nivel INT NOT NULL,
    texto VARCHAR(1000) NOT NULL,
    custo_ouro INT NOT NULL,

    CONSTRAINT fk_dica_desafio
    FOREIGN KEY (desafio_id)
    REFERENCES jogo.desafios(id)
    ON DELETE CASCADE,

    CONSTRAINT uk_dica_nivel
    UNIQUE (desafio_id, nivel),

    CONSTRAINT ck_dica_nivel
    CHECK (nivel BETWEEN 1 AND 3)
    );


CREATE TABLE IF NOT EXISTS jogo.itens (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    descricao VARCHAR(1000),
    tipo VARCHAR(50),
    capitulo_desbloqueio INT,

    CONSTRAINT fk_item_capitulo
    FOREIGN KEY (capitulo_desbloqueio)
    REFERENCES jogo.capitulos(id)
    );

