-- ___________________
-- SCHEMA DO REINO
-- ___________________

CREATE SCHEMA IF NOT EXISTS reino;

CREATE TABLE IF NOT EXISTS reino.vilas (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    regiao VARCHAR(50) NOT NULL,
    populacao INT,
    status VARCHAR(20)
    );

CREATE TABLE IF NOT EXISTS reino.habitantes (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    idade INT,
    profissao VARCHAR(80),
    vila_id INT,
    status VARCHAR(20),

    CONSTRAINT fk_habitante_vila
    FOREIGN KEY (vila_id)
    REFERENCES reino.vilas(id)
    );

CREATE TABLE IF NOT EXISTS reino.soldados (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    nivel INT,
    classe VARCHAR(50),
    vila_id INT,
    status VARCHAR(20),

    CONSTRAINT fk_soldado_vila
    FOREIGN KEY (vila_id)
    REFERENCES reino.vilas(id)
    );

CREATE TABLE IF NOT EXISTS reino.armas (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    tipo VARCHAR(50),
    poder INT,
    raridade VARCHAR(30),
    soldado_id INT,

    CONSTRAINT fk_arma_soldado
    FOREIGN KEY (soldado_id)
    REFERENCES reino.soldados(id)
    );

CREATE TABLE IF NOT EXISTS reino.recursos (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    tipo VARCHAR(50),
    quantidade INT,
    vila_id INT,

    CONSTRAINT fk_recurso_vila
    FOREIGN KEY (vila_id)
    REFERENCES reino.vilas(id)
    );

CREATE TABLE IF NOT EXISTS reino.entregas (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recurso_id INT,
    origem_vila_id INT,
    destino_vila_id INT,
    quantidade INT,
    data_entrega DATE,
    status VARCHAR(20),

    CONSTRAINT fk_entrega_recurso
    FOREIGN KEY (recurso_id)
    REFERENCES reino.recursos(id),

    CONSTRAINT fk_entrega_origem
    FOREIGN KEY (origem_vila_id)
    REFERENCES reino.vilas(id),

    CONSTRAINT fk_entrega_destino
    FOREIGN KEY (destino_vila_id)
    REFERENCES reino.vilas(id)
    );

CREATE TABLE IF NOT EXISTS reino.criaturas (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    tipo VARCHAR(50),
    nivel INT,
    regiao VARCHAR(50),
    status VARCHAR(20)
    );


CREATE TABLE IF NOT EXISTS reino.mensagens (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    remetente VARCHAR(100),
    destinatario VARCHAR(100),
    assunto VARCHAR(150),
    conteudo VARCHAR(2000),
    data_envio TIMESTAMP,
    prioridade VARCHAR(20)
    );

CREATE TABLE IF NOT EXISTS reino.registros_corrompidos (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_registro VARCHAR(50),
    registro_id INT,
    regiao VARCHAR(50),
    nivel_corrupcao INT,
    data_corrupcao DATE,
    status VARCHAR(20)
    );


